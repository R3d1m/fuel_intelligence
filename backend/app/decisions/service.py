"""Decision Service and Recommendation Orchestrator.

Coordinates:
1. Transforming ConstrainedPlanner actions into contextual, explainable Recommendation objects.
2. Managing lifecycle state machine (PROPOSED -> APPROVED/REJECTED -> SUBMITTED/FAILED).
3. Dispatching approved allocations to the upstream simulator with deterministic idempotency keys.
4. Handling and mapping simulator rejection codes to actionable operator guidance.
5. Recording all events, state transitions, and context inputs in the SQLite AuditLedger.
"""

from __future__ import annotations

import logging
from datetime import UTC, datetime
from typing import Any

from app.adapters.errors import SimulatorError
from app.adapters.simulator_client import SimulatorClient
from app.config import Settings, get_settings
from app.decisions.audit import AuditLedger
from app.decisions.models import (
    Recommendation,
    RecommendationStatus,
    map_simulator_error_code,
)
from app.domain.models import AllocationCreate, SimulatorSnapshot
from app.ingest.store import StateStore
from app.intelligence.planner import ConstrainedPlanner, DispatchPlan

logger = logging.getLogger(__name__)


class DecisionService:
    """Core domain service orchestrating recommendation generation, approval, and dispatches."""

    def __init__(
        self,
        client: SimulatorClient,
        audit_ledger: AuditLedger,
        planner: ConstrainedPlanner,
        store: StateStore | None = None,
        settings: Settings | None = None,
    ) -> None:
        self.client = client
        self.audit_ledger = audit_ledger
        self.planner = planner
        self.store = store
        self.settings = settings or get_settings()

    def generate_recommendations_from_plan(
        self,
        plan: DispatchPlan,
        snapshot: SimulatorSnapshot,
    ) -> list[Recommendation]:
        """Convert a DispatchPlan into durable recommendations, saving them to the audit ledger."""
        recommendations: list[Recommendation] = []

        # Index station telemetry for signals context
        station_map = {s.id: s for s in snapshot.stations}

        for action in plan.actions:
            station = station_map.get(action.station_id)
            inv = station.inventory.get(action.fuel_type, 0.0) if station else 0.0
            cap = station.capacity.get(action.fuel_type, 1.0) if station else 1.0
            fill_pct = (inv / cap) * 100.0 if cap > 0 else 0.0

            signals: dict[str, Any] = {
                "station_fill_percent": round(fill_pct, 1),
                "current_inventory_liters": inv,
                "tank_capacity_liters": cap,
                "demand_multiplier": station.demand_multiplier if station else 1.0,
                "departure_tick": action.departure_tick,
                "transit_ticks": action.transit_ticks,
                "is_timely": action.is_timely,
            }

            is_fallback = getattr(plan, "is_fallback", False) or getattr(
                action, "is_fallback", False
            )
            signals["is_fallback"] = is_fallback
            if getattr(plan, "fallback_reason", None):
                signals["fallback_reason"] = plan.fallback_reason

            rec = Recommendation.from_plan_action(
                action=action,
                plan_id=plan.plan_id,
                created_tick=snapshot.current_tick,
                confidence_score=action.confidence_score,
                confidence_level=action.confidence_level,
                needs_human_review=action.needs_human_review,
                signals=signals,
            )

            # Check if this exact idempotency key was already recorded
            existing = self.audit_ledger.get_recommendation_by_idempotency_key(rec.idempotency_key)
            if existing:
                recommendations.append(existing)
                continue

            # Durable audit recording
            raw_inputs: dict[str, Any] = {
                "plan_id": plan.plan_id,
                "current_tick": snapshot.current_tick,
                "action": action.model_dump(),
                "signals": signals,
            }
            self.audit_ledger.save_recommendation(rec, raw_inputs=raw_inputs)

            event_type = "FALLBACK_POLICY_ACTIVATED" if is_fallback else "PROPOSAL_CREATED"
            reason = getattr(plan, "fallback_reason", "degraded mode")
            op_notes = (
                f"Generated by emergency fallback policy ({reason}); human review mandated."
                if is_fallback
                else "Automatically generated by ConstrainedPlanner"
            )

            self.audit_ledger.record_audit_event(
                recommendation_id=rec.recommendation_id,
                event_type=event_type,
                from_status=None,
                to_status=RecommendationStatus.PROPOSED.value,
                operator_notes=op_notes,
                details={
                    "station_id": rec.station_id,
                    "fuel_type": rec.fuel_type.value,
                    "quantity": rec.quantity_liters,
                    "bottleneck": rec.constraints.bottleneck_constraint.value,
                    "is_fallback": is_fallback,
                    "needs_human_review": rec.needs_human_review,
                },
            )
            recommendations.append(rec)

        return recommendations

    def generate_recommendations_from_snapshot(
        self,
        snapshot: SimulatorSnapshot,
        force_fallback: bool = False,
    ) -> list[Recommendation]:
        """Formulate a fresh dispatch plan and generate durable recommendations."""
        try:
            plan = self.planner.generate_plan(snapshot, force_fallback=force_fallback)
        except Exception as exc:
            logger.warning(
                "Planner execution failed in DecisionService (%s: %s). Activating FallbackPlanner.",
                type(exc).__name__,
                exc,
            )
            from app.intelligence.fallback import FallbackPlanner

            fallback = getattr(self.planner, "fallback_planner", None) or FallbackPlanner(
                settings=self.settings
            )
            plan = fallback.generate_plan(snapshot, fallback_reason=f"Planner threw error: {exc}")

        return self.generate_recommendations_from_plan(plan, snapshot)

    def get_recommendation(self, recommendation_id: str) -> Recommendation | None:
        """Fetch recommendation by ID."""
        return self.audit_ledger.get_recommendation(recommendation_id)

    def list_recommendations(
        self,
        status: RecommendationStatus | str | None = None,
        station_id: str | None = None,
        limit: int = 100,
    ) -> list[Recommendation]:
        """Query recommendations with optional filtering."""
        return self.audit_ledger.list_recommendations(
            status=status, station_id=station_id, limit=limit
        )

    async def approve_recommendation(
        self,
        recommendation_id: str,
        operator_notes: str | None = None,
    ) -> Recommendation:
        """Approve a recommendation and dispatch the allocation to the upstream simulator.

        Transitions:
        - PROPOSED (or FAILED retry) -> APPROVED -> SUBMITTED (on success)
        - PROPOSED (or FAILED retry) -> APPROVED -> FAILED (on error)
        """
        rec = self.audit_ledger.get_recommendation(recommendation_id)
        if rec is None:
            raise ValueError(f"Recommendation '{recommendation_id}' not found.")

        # Guard against invalid transitions
        if rec.status == RecommendationStatus.SUBMITTED:
            raise ValueError(
                f"Recommendation '{recommendation_id}' has already been submitted to the simulator."
            )
        if rec.status == RecommendationStatus.REJECTED:
            raise ValueError(
                f"Recommendation '{recommendation_id}' was rejected. Cannot approve rejected item."
            )

        from_status = rec.status.value
        rec.status = RecommendationStatus.APPROVED
        rec.approved_at = datetime.now(UTC)
        if operator_notes:
            rec.operator_notes = operator_notes

        self.audit_ledger.save_recommendation(rec)
        self.audit_ledger.record_audit_event(
            recommendation_id=rec.recommendation_id,
            event_type="DECISION_APPROVED",
            from_status=from_status,
            to_status=RecommendationStatus.APPROVED.value,
            operator_notes=operator_notes,
            details={
                "idempotency_key": rec.idempotency_key,
                "quantity": rec.quantity_liters,
            },
        )

        # Build simulator dispatch payload
        alloc_create = AllocationCreate(
            idempotency_key=rec.idempotency_key,
            source_depot_id=rec.source_depot_id,
            destination_station_id=rec.station_id,
            route_id=rec.route_id,
            fuel_type=rec.fuel_type,
            quantity=rec.quantity_liters,
        )

        try:
            resp = await self.client.create_allocation(alloc_create)
            alloc = resp.data

            rec.status = RecommendationStatus.SUBMITTED
            rec.submitted_at = datetime.now(UTC)
            rec.simulator_allocation_id = alloc.id
            rec.failure_code = None
            rec.failure_reason = None
            self.audit_ledger.save_recommendation(rec)

            self.audit_ledger.record_audit_event(
                recommendation_id=rec.recommendation_id,
                event_type="ALLOCATION_SUBMITTED",
                from_status=RecommendationStatus.APPROVED.value,
                to_status=RecommendationStatus.SUBMITTED.value,
                operator_notes=operator_notes,
                details={
                    "simulator_allocation_id": alloc.id,
                    "status": str(alloc.status),
                    "departure_tick": alloc.departure_tick,
                    "expected_arrival_tick": alloc.expected_arrival_tick,
                },
            )
            logger.info(
                "Successfully dispatched allocation %d for recommendation %s to %s",
                alloc.id,
                rec.recommendation_id,
                rec.station_name,
            )
            return rec

        except SimulatorError as err:
            err_code = getattr(err, "code", "SIMULATOR_ERROR")
            err_msg = getattr(err, "message", str(err))
            guidance = map_simulator_error_code(err_code, err_msg)

            rec.status = RecommendationStatus.FAILED
            rec.failure_code = err_code
            rec.failure_reason = guidance
            self.audit_ledger.save_recommendation(rec)

            self.audit_ledger.record_audit_event(
                recommendation_id=rec.recommendation_id,
                event_type="ALLOCATION_FAILED",
                from_status=RecommendationStatus.APPROVED.value,
                to_status=RecommendationStatus.FAILED.value,
                operator_notes=operator_notes,
                details={
                    "error_code": err_code,
                    "error_message": err_msg,
                    "guidance": guidance,
                },
            )
            logger.warning(
                "Allocation dispatch failed for recommendation %s: [%s] %s",
                rec.recommendation_id,
                err_code,
                guidance,
            )
            return rec

        except Exception as exc:
            err_code = "UNEXPECTED_ERROR"
            err_msg = str(exc)
            guidance = f"Unexpected error during allocation submission: {err_msg}"

            rec.status = RecommendationStatus.FAILED
            rec.failure_code = err_code
            rec.failure_reason = guidance
            self.audit_ledger.save_recommendation(rec)

            self.audit_ledger.record_audit_event(
                recommendation_id=rec.recommendation_id,
                event_type="ALLOCATION_FAILED",
                from_status=RecommendationStatus.APPROVED.value,
                to_status=RecommendationStatus.FAILED.value,
                operator_notes=operator_notes,
                details={
                    "error_code": err_code,
                    "error_message": err_msg,
                },
            )
            logger.exception("Unexpected error submitting allocation for %s", rec.recommendation_id)
            return rec

    def reject_recommendation(
        self,
        recommendation_id: str,
        operator_notes: str | None = None,
    ) -> Recommendation:
        """Reject a recommendation, recording the rationale in the audit ledger."""
        rec = self.audit_ledger.get_recommendation(recommendation_id)
        if rec is None:
            raise ValueError(f"Recommendation '{recommendation_id}' not found.")

        if rec.status == RecommendationStatus.SUBMITTED:
            raise ValueError(
                f"Recommendation '{recommendation_id}' has already been submitted to the simulator."
            )
        if rec.status == RecommendationStatus.REJECTED:
            return rec  # Idempotent rejection

        from_status = rec.status.value
        rec.status = RecommendationStatus.REJECTED
        rec.rejected_at = datetime.now(UTC)
        if operator_notes:
            rec.operator_notes = operator_notes

        self.audit_ledger.save_recommendation(rec)
        self.audit_ledger.record_audit_event(
            recommendation_id=rec.recommendation_id,
            event_type="DECISION_REJECTED",
            from_status=from_status,
            to_status=RecommendationStatus.REJECTED.value,
            operator_notes=operator_notes,
            details={
                "rationale": operator_notes or "Operator rejected recommendation without note."
            },
        )
        logger.info("Recommendation %s rejected by operator.", rec.recommendation_id)
        return rec

    def get_audit_history(
        self,
        recommendation_id: str | None = None,
        limit: int = 100,
    ) -> list[dict[str, Any]]:
        """Retrieve audit log history."""
        return self.audit_ledger.get_audit_events(recommendation_id=recommendation_id, limit=limit)

    def get_audit_statistics(self) -> dict[str, Any]:
        """Retrieve audit statistics and decision metrics."""
        return self.audit_ledger.get_audit_statistics()
